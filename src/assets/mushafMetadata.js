/**
 * Get the exact Madinah Mushaf page (1 to 604) for a given Surah and Ayah.
 * @param {number} surahNumber
 * @param {number} ayahNumber
 * @returns {number} Page number from 1 to 604
 */
export const getPageForAyah = (surahNumber, ayahNumber) => {
  const s = Number(surahNumber);
  const a = Number(ayahNumber || 1);

  for (let i = 0; i < MUSHAF_PAGES.length; i += 1) {
    const p = MUSHAF_PAGES[i];
    // Check if (s, a) falls between start and end of page p
    const isAfterStart = s > p.startSurah || (s === p.startSurah && a >= p.startAyah);
    const isBeforeEnd = s < p.endSurah || (s === p.endSurah && a <= p.endAyah);

    if (isAfterStart && isBeforeEnd) {
      return p.page;
    }
  }

  // Fallback clamping
  return 1;
};

/**
 * Get the full metadata for a specific Mushaf page.
 * @param {number} pageNumber
 */
export const getMushafPageInfo = (pageNumber) => {
  const clamped = Math.max(1, Math.min(604, Number(pageNumber) || 1));
  return MUSHAF_PAGES[clamped - 1] || MUSHAF_PAGES[0];
};

